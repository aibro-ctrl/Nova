/** Раздел внутри версии: «Маршруты», «Здоровье», «Напоминания» — чтобы новости читались по темам. */
data class ReleaseSection(val title: String, val items: List<String>)

/** Одна версия в списке «Что нового»: название и разделы с короткими пунктами. */
data class Release(val version: String, val title: String, val sections: List<ReleaseSection>) {
    /** Все пункты подряд — для подписей и проверок. */
    val changes: List<String> get() = sections.flatMap { it.items }
}

