package ai.nova.core.nlp

/**
 * Род имени: от него зависит, каким голосом говорит Нова и в каком роде она о себе рассказывает.
 *
 * Полноценного словаря имён в приложении нет, поэтому правило простое и предсказуемое:
 * «а»/«я» на конце — женское имя, согласная, «й» и «ь» — мужское, остальное — не определить.
 * Исключения — частые мужские имена на «а»/«я» (Никита, Илья) и неоднозначные (Саша, Женя):
 * для неоднозначных род не угадываем, чтобы не обращаться к человеку неправильно.
 */
enum class Gender {
    FEMININE,
    MASCULINE,

    /** Не определить: имя не склоняется или подходит и мужчине, и женщине. */
    NEUTRAL;

    val isMasculine: Boolean get() = this == MASCULINE
    val isFeminine: Boolean get() = this == FEMININE

    /** «женский», «мужской» — для подписей в настройках. */
    val label: String
        get() = when (this) {
            FEMININE -> "женский"
            MASCULINE -> "мужской"
            NEUTRAL -> "не определён"
        }

    companion object {
        /** Мужские имена, которые оканчиваются на «а»/«я». */
        private val MALE_ON_A = setOf(
            "никита", "илья", "кузьма", "фома", "лука", "савва", "данила", "гаврила", "гоша", "миша",
            "паша", "дима", "лёша", "леша", "алёша", "алеша", "слава", "юра", "ванюша", "ваня", "петя",
            "вася", "коля", "толя", "витя", "костя", "гена", "сева", "гриша", "яша", "рома", "вова",
            "дёма", "дема", "тёма", "тема", "серёжа", "сережа", "андрюша", "игорёша", "игореша", "лёва", "лева",
        )

        /** Женские имена на мягкий знак. */
        private val FEMALE_SOFT = setOf("любовь", "руфь", "нинель", "рахиль", "эсфирь", "юдифь", "ассоль", "суламифь")

        /** Подходят и мужчине, и женщине: род не угадываем, чтобы не обратиться неправильно. */
        private val AMBIGUOUS = setOf("саша", "женя", "валя", "шура", "саня", "слава")

        /** Род имени; [Gender.NEUTRAL], если имя пустое или угадать нельзя. */
        fun of(name: String?): Gender {
            val n = RuTokenizer.normalize(name.orEmpty()).trim().trim('-', '.', ' ')
                // «Саня, помоги» → «саня»; уменьшительные вроде «Саня» и «Соня» считаем по окончанию.
                .substringBefore(' ').substringBefore('-')
            if (n.isEmpty()) return NEUTRAL
            if (n in AMBIGUOUS) return NEUTRAL
            if (n in MALE_ON_A) return MASCULINE
            if (n in FEMALE_SOFT) return FEMININE
            return when (n.last()) {
                'а', 'я' -> FEMININE
                'б', 'в', 'г', 'д', 'ж', 'з', 'к', 'л', 'м', 'н', 'п', 'р', 'с', 'т', 'ф', 'х', 'ц', 'ч', 'ш', 'щ', 'й', 'ь' -> MASCULINE
                else -> NEUTRAL
            }
        }

        /**
         * Род ассистента: по его имени. Неизменяемое имя (например, «Нова» → женский) —
         * на всякий случай женский, потому что так Нова и задумана.
         */
        fun ofAssistant(name: String?): Gender = of(name).takeIf { it != NEUTRAL } ?: FEMININE
    }
}
