/**
 * Согласование рода в готовом тексте Нова.
 *
 * Все ответы в приложении написаны в женском роде («Записала», «Поняла», «Готова»), потому что
 * по умолчанию Нова — женское имя. Если ассистента зовут мужским именем (Джарвис, Максим), те же
 * фразы нужно сказать в мужском роде — иначе получается «мужской голос отвечает о себе в женском роде».
 *
 * Меняются только формы первого лица про себя («записала → записал») и краткие прилагательные
 * («готова → готов»). Обращение к пользователю идёт на «вы» и в роде не нуждается, чужие слова
 * в кавычках не трогаются: список форм задан явно, а не правилом «убрать последнюю букву»,
 * иначе «нашла» превратилось бы в «нашл».
 */
