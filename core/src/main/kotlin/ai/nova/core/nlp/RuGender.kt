    /** Возвратные глаголы: «проснулась → проснулся», «ошиблась → ошибся». */
    private fun reflexive(key: String): String? = when {
        // «проснулась → проснулся», но «ошиблась → ошибся»: окончание зависит от того, гласная или
        // согласная стоит перед «-лась», иначе получается «ошился».
        key.endsWith("лась") -> run {
            val stem = key.dropLast(4)
            if (stem.lastOrNull() in setOf('а', 'е', 'ё', 'и', 'о', 'у', 'ы', 'э', 'ю', 'я')) stem + "лся" else stem + "ся"
        }
        key.endsWith("ась") && key.length > 5 -> key.dropLast(2) + "ся"
        else -> null
    }

    /**
     * Текст в мужском роде: «Записала заметку» → «Записал заметку». Женский и неопределённый — без изменений.
     * Чужие слова в кавычках не трогаются: в «Была в парке» — название заметки, а не речь Новы.
     */
    fun masculine(text: String): String {
        if (text.isEmpty()) return text
        val sb = StringBuilder(text.length)
        var i = 0
        while (i < text.length) {
            val c = text[i]
            // Кавычки: «…», „…“, "…" — пропускаем как есть, чтобы не менять содержимое.
            if (c in QUOTES_OPEN) {
                val close = QUOTES_CLOSE.getValue(c)
                val end = text.indexOf(close, i + 1)
                val upto = if (end < 0) text.length else end + 1
                sb.append(text, i, upto)
                i = upto
                continue
            }
            if (!c.isLetter() || c !in 'а'..'я' && c !in 'А'..'Я' && c != 'ё' && c != 'Ё') { sb.append(c); i++; continue }
            var j = i
            while (j < text.length && (text[j].isLetter() && (text[j] in 'а'..'я' || text[j] in 'А'..'Я' || text[j] == 'ё' || text[j] == 'Ё'))) j++
            val word = text.substring(i, j)
            sb.append(masculineWord(word))
            i = j
        }
        return sb.toString()
    }

    private val QUOTES_OPEN = setOf('«', '„', '"', '“')
    private val QUOTES_CLOSE = mapOf('«' to '»', '„' to '“', '"' to '"', '“' to '”')

    private fun masculineWord(word: String): String {
        val lower = word.lowercase().replace('ё', 'е')
        val male = MASCULINE[lower] ?: reflexive(lower) ?: return word
        return if (word.first().isUpperCase()) male.replaceFirstChar { it.uppercase() } else male
    }

    /** Текст в нужном роде: для женского и неопределённого рода ничего не меняется. */
    fun agree(text: String, gender: Gender): String = if (gender.isMasculine) masculine(text) else text
}
