            молоко или вода — 250 мл
            соль — щепотка
            сахар — 1 ч. ложка
            """,
            """
            Доведите жидкость до кипения и добавьте соль и сахар.
            Всыпьте хлопья и варите, помешивая, 5–7 минут.
            Снимите с огня и дайте постоять минуту под крышкой.
            """,
        ),
    )

    /** Рецепт из книги (без интернета). */
    fun book(dish: String): KitchenRecipe? {
        val want = ai.nova.core.nlp.TextAnalysis.stems(dish).toSet()
        if (want.isEmpty()) return null
        var best: Entry? = null
        var bestScore = 0
        for (entry in BOOK) {
            val keys = ai.nova.core.nlp.TextAnalysis.stems(entry.title + " " + entry.keys.joinToString(" ")).toSet()
            val score = want.count { w -> keys.any { k -> k.startsWith(w.take(4)) || w.startsWith(k.take(4)) } }
            if (score > bestScore) { best = entry; bestScore = score }
        }
        // Совпала хотя бы половина слов: «плов узбекский» и «тесто на хлеб» — да, «что-то с курицей» — нет.
        return best?.takeIf { bestScore * 2 >= want.size }?.toRecipe()
    }

    /**
     * Рецепт из текста статьи (Википедия/Викиучебник): блок ингредиентов и блок приготовления.
     * Возвращает null, если разобрать нечего — тогда лучше честно сказать, что рецепта нет.
     */
    fun fromText(title: String, text: String): KitchenRecipe? {
        val lines = text.lines().map { it.trim() }.filter { it.isNotEmpty() }
        if (lines.isEmpty()) return null
        val ingHead = Rx.of("""^(?:ингредиенты|состав|продукты|вам\s+понадобится|понадобится|что\s+нужно)\b[^.]{0,40}$""")
        val stepHead = Rx.of("""^(?:приготовление|способ\s+приготовления|технология\s+приготовления|пошагов\w*\s+рецепт|шаги|ход\s+работы|как\s+готовить)\b[^.]{0,40}$""")
        val ingredients = ArrayList<String>()
        val stepLines = ArrayList<String>()
        var mode = 0 // 0 — до разделов, 1 — ингредиенты, 2 — шаги
        for (line in lines) {
            val low = RuTokenizer.normalize(line)
            when {
                stepHead.containsMatchIn(low) -> mode = 2
                ingHead.containsMatchIn(low) -> mode = 1
                mode == 1 && looksLikeIngredient(line) -> ingredients += cleanLine(line)
                mode == 1 -> mode = 2
                mode == 2 -> stepLines += line
                else -> Unit
            }
        }
        val steps = buildSteps(stepLines.ifEmpty { lines })
        val ings = ingredients.distinct().take(20)
        if (steps.size < 2) return null
        return KitchenRecipe.of(
            title.replace(Rx.of("""(?iu)^рецепт[:\s]+"""), "").ifBlank { title },
            ings,
            steps.take(12),
            source = "статья",
        )
    }

    private fun looksLikeIngredient(line: String): Boolean {
        if (Rx.of("""^\s*\d+[.)]\s""").containsMatchIn(line)) return false
        val clean = cleanLine(line)
        val words = clean.split(Rx.of("""\s+""")).size
        return clean.length in 3..90 && words <= 12 && !Rx.of("""(?iu)^(?:итак|затем|после|далее|когда|если)\b""").containsMatchIn(clean)
    }

    private fun cleanLine(line: String): String = line.trim().trimStart('•', '*', '-', '—', ' ').trim()

    /** Шаги из связного текста: нумерованные строки как есть, иначе — предложения по 60–220 символов. */
    private fun buildSteps(lines: List<String>): List<String> {
        val numbered = lines.filter { Rx.of("""^\s*\d+[.)]\s""").containsMatchIn(it) }
        if (numbered.size >= 2) return numbered.map { cleanLine(it.replace(Rx.of("""^\s*\d+[.)]\s*"""), "")) }.filter { it.length > 10 }
        val sentences = lines.joinToString(" ")
            .split(Rx.of("""(?<=[.!?])\s+(?=\p{Lu})"""))
            .map { it.trim() }
            .filter { it.length > 25 }
        val steps = ArrayList<String>()
        var acc = StringBuilder()
        for (s in sentences) {
            if (acc.isNotEmpty() && acc.length + s.length > 200) { steps += acc.toString(); acc = StringBuilder() }
            if (acc.isNotEmpty()) acc.append(' ')
            acc.append(s)
            if (acc.length >= 120) { steps += acc.toString(); acc = StringBuilder() }
        }
        if (acc.isNotEmpty()) steps += acc.toString()
        return steps.map { it.trim() }
    }
