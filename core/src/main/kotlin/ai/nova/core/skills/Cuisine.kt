import ai.nova.core.nlp.RuTokenizer
import ai.nova.core.nlp.Rx

/**
 * Рецепт для готовки: ингредиенты с количествами и шаги.
 * [servings] — на сколько порций рассчитана книга; от него считается пересчёт («на 6 порций»).
 * [source] — откуда рецепт (книга Нова, Википедия, заметка) — для «откуда это».
 */
@kotlinx.serialization.Serializable
data class KitchenRecipe(
    val title: String,
    val ingredients: List<RecipeIngredient> = emptyList(),
    val steps: List<String> = emptyList(),
    val servings: Int = DEFAULT_SERVINGS,
    val source: String? = null,
) {
    /** Ингредиенты строками — для карточки, заметки и списка покупок. */
    val ingredientTexts: List<String> get() = ingredients.map { it.text }

    /** Представление для режима готовки: ингредиенты одной строкой. */
    fun toRecipe(): Recipe = Recipe(title, ingredientTexts.joinToString(", ").ifEmpty { null }, steps)

    fun hasIngredients(): Boolean = ingredients.isNotEmpty()

    /** Пересчёт на [servings] порций: количества умножаются, «по вкусу» не трогаем. */
    fun scaled(servings: Int): KitchenRecipe {
        if (servings <= 0 || servings == this.servings || this.servings <= 0) return this
        val factor = servings.toDouble() / this.servings
        return copy(servings = servings, ingredients = ingredients.map { it.scaled(factor) })
    }

    companion object {
        /** По умолчанию книга рецептов рассчитана на четверых. */
        const val DEFAULT_SERVINGS = 4

        /** Рецепт из строк: «рис — 500 г» разбирается в количество и единицу. */
        fun of(
            title: String,
            ingredients: List<String>,
            steps: List<String>,
            servings: Int = DEFAULT_SERVINGS,
            source: String? = null,
        ): KitchenRecipe = KitchenRecipe(title, RecipeIngredient.parseAll(ingredients), steps, servings, source)
    }
}

/**
 * Кухня: «как приготовить плов», «что нужно для теста на хлеб», «из чего готовят борщ».
 * Сначала — своя книга рецептов (работает без интернета), потом — статья из Википедии/Викиучебника.
 */
object Cuisine {
    // ------------------------------------------------------------------ Фразы

    /** «Как приготовить…», «как сварить…» — это точно про готовку. */
    private val HOW_STRONG = Rx.of(
        """^(?:нова[,!]?\s*)?(?:а\s+|ну\s+|и\s+)?как\s+(?:приготовить|приготовлю|приготовим|сварить|испечь|готовить|готовится|зажарить|пожарить|потушить|запечь|засолить|замариновать)\s+(.+)$""",
    )

    /** «Как сделать тесто» — про готовку, только если такое блюдо известно: «как сделать уроки быстрее» — не рецепт. */
    private val HOW_WEAK = Rx.of("""^(?:нова[,!]?\s*)?(?:а\s+|ну\s+|и\s+)?как\s+(?:сделать|сделаю)\s+(.+)$""")
    private val NEED = Rx.of(
        """^(?:нова[,!]?\s*)?(?:а\s+)?(?:что|чего|какие\s+продукты)\s+(?:нужно|надо|требуется|понадобится|брать)\s*(?:чтобы\s+)?(?:приготовить|сварить|испечь|сделать|для)?\s*(.+)$""",
    )
    private val FROM = Rx.of(
        """^(?:нова[,!]?\s*)?(?:а\s+)?из\s+чего\s+(?:готовят|готовить|делают|сделать|состоит|состоят|приготовить)\s+(.+)$|^(?:нова[,!]?\s*)?(?:а\s+)?из\s+чего\s+(.+)$""",
    )
    private val RECIPE_WORD = Rx.of("""^(?:нова[,!]?\s*)?(?:а\s+)?(?:дай|дайте|подскажи|расскажи|напомни)?\s*рецепт\w*\s+(.+)$""")

    /** Согласие на предложение: «да», «давай», «конечно», «да, добавь». */
    private val AGREE = Rx.of("""^(?:да|давай|давайте|конечно|ага|угу|хорошо|ок|окей|да,?\s+(?:давай|добавь|конечно|помоги|приготовим))\b.*$""")

    /** «Добавь в покупки» в ответ на предложение. */
    private val TO_SHOPPING = Rx.of("""(?:добав|запиши|занеси|внеси)\w*\s+(?:это\s+|всё\s+|все\s+|ингредиенты\s+)?(?:в|во)\s+(?:покупки|список\s+покупок|список|продукты)|^(?:в\s+)?покупки$|^список\s+покупок$""")

    /** «Помоги приготовить» в ответ на предложение. */
    private val TO_STEPS = Rx.of("""(?:помоги|помочь|начни|начн[её]м|давай)\s+(?:мне\s+)?(?:приготовить|готовить|по\s+шагам|пошагово)|^по\s+шагам$|^пошагово$""")

    /** Название блюда из вопроса о рецепте; null — это не вопрос о приготовлении. */
    fun dish(text: String): String? = ask(text)?.dish

    /** Вопрос о рецепте: [strong] — явно про готовку («как приготовить X»), отвечаем даже без рецепта. */
    data class Ask(val dish: String, val strong: Boolean)

    fun ask(text: String): Ask? {
        val t = RuTokenizer.normalize(text).trim().trimEnd('.', '!').trim()
        if (t.isEmpty()) return null
        HOW_STRONG.find(t)?.groupValues?.get(1)?.let { return cleanDish(it).takeIf { d -> d.length >= 2 }?.let { d -> Ask(d, true) } }
        HOW_WEAK.find(t)?.groupValues?.get(1)?.let { return cleanDish(it).takeIf { d -> d.length >= 2 }?.let { d -> Ask(d, false) } }
        val strong = RECIPE_WORD.find(t)?.groupValues?.get(1)
        if (strong != null) return cleanDish(strong).takeIf { it.length >= 2 }?.let { Ask(it, false) }
        val raw = NEED.find(t)?.groupValues?.get(1)
            ?: FROM.find(t)?.let { m -> m.groupValues[1].ifBlank { m.groupValues[2] } }
            ?: return null
        val dish = cleanDish(raw)
        return dish.takeIf { it.length >= 2 }?.let { Ask(it, false) }
    }

    fun agrees(text: String): Boolean = AGREE.containsMatchIn(RuTokenizer.normalize(text).trim().trimEnd('.', '!', '?'))

    fun wantsShopping(text: String): Boolean = TO_SHOPPING.containsMatchIn(RuTokenizer.normalize(text).trim().trimEnd('.', '!', '?'))

    fun wantsSteps(text: String): Boolean = TO_STEPS.containsMatchIn(RuTokenizer.normalize(text).trim().trimEnd('.', '!', '?'))

    /**
     * «пересчитай на 6 порций», «на 2 порции», «на четверых» — сколько порций нужно.
     * null — в фразе нет пересчёта.
     */
    fun servingsRequest(text: String): Int? {
        val t = RuTokenizer.normalize(text).trim().trimEnd('.', '!', '?')
        Regex("""(?:пересчита\p{L}*|рассчита\p{L}*|сделай|приготовь|давай)?\s*(?:на|для)\s+(\d{1,2})\s*порц\p{L}*""")
            .find(t)?.groupValues?.get(1)?.toIntOrNull()?.let { return it.takeIf { n -> n in 1..30 } }
        Regex("""(?:пересчита\p{L}*|рассчита\p{L}*)\s+(?:все\s+)?на\s+(\d{1,2})\b""")
            .find(t)?.groupValues?.get(1)?.toIntOrNull()?.let { return it.takeIf { n -> n in 1..30 } }
        val words = mapOf(
            "одного" to 1, "двоих" to 2, "троих" to 3, "четверых" to 4, "пятерых" to 5,
            "шестерых" to 6, "семерых" to 7, "восьмерых" to 8,
        )
        Regex("""(?:на|для)\s+(одного|двоих|троих|четверых|пятерых|шестерых|семерых|восьмерых)\b""")
            .find(t)?.groupValues?.get(1)?.let { return words[it] }
        return null
    }

    /** «тесто на хлеб, пожалуйста» → «тесто на хлеб». */
    private fun cleanDish(raw: String): String = raw
        .replace(Rx.of("""(?iu)\s+(?:по\s+)?рецепт\w*\s*$"""), "")
        .replace(Rx.of("""(?iu)\s+(?:пожалуйста|мне|сейчас|сегодня)\s*$"""), "")
        .trim().trim('.', ',', '!', '?', ':', '«', '»', '—', '-').trim()

