package ai.nova.core.ai

/**
 * Офлайн-модель на телефоне (llama.cpp): отвечает на свободные вопросы без интернета и ключей.
 * Команды (записать, напомнить…) она не выполняет — только разговор, советы, объяснения, тексты.
 */
interface LocalChat {
    /** Модель скачана и может отвечать. */
    val available: Boolean

    /**
     * Можно ли ждать ответа прямо сейчас. В фоне Android душит процесс (cpuset «restricted»,
     * замер на Galaxy A56: 14 токенов/с на экране против 0,2 в фоне) — там честнее сказать
     * «включите экран», чем молчать минуту.
     */
    val canAnswerNow: Boolean get() = true

    /**
     * Ответ на реплику с учётом недавнего разговора; null — не получилось.
     * [onChunk] получает куски по мере генерации: озвучка начинает говорить, не дожидаясь всего текста.
     */
    suspend fun reply(
        system: String,
        history: List<ChatMessage>,
        maxTokens: Int = 96,
        onChunk: ((String) -> Unit)? = null,
    ): String?

    companion object {
        /** Реплика — вопрос или просьба к собеседнику, а не команда и не заметка. */
        fun looksLikeChat(text: String): Boolean {
            val t = text.trim().lowercase().replace('ё', 'е')
            if (t.endsWith("?")) return true
            return Regex(
                """^(?:а\s+|и\s+|слушай[,]?\s+|скажи[,]?\s+)?(?:почему|зачем|как|что|кто|где|когда|сколько|какой|какая|какое|какие|каким|чем|откуда|куда|чей|можно ли|стоит ли|правда ли|нужно ли|надо ли|расскажи|объясни|посоветуй|придумай|напиши|сочини|помоги|подскажи|переведи|поговори|давай поговорим|давай обсудим|как думаешь|что думаешь|ты знаешь|ты умеешь|ты любишь|ты можешь|кто лучше|что лучше|в чем разница)(?:\s|$)""",
            ).containsMatchIn(t) || Regex("""(?:^|\s)ли(?:\s|$)""").containsMatchIn(t) ||
                // «А как у тебя?» — вопрос к собеседнику, хотя начинается не с вопросительного слова.
                Regex("""(?:^|\s)(?:а\s+)?(?:как\s+у\s+тебя|у\s+тебя\s+как|как\s+сам\w*)(?:\s|$)""").containsMatchIn(t)
        }

        /** Короткая реплика-реакция без команды: «всё хорошо», «спасибо», «скучно», «устала». */
        fun isSmallTalk(text: String): Boolean {
            val t = text.trim().lowercase().replace('ё', 'е').trimEnd('?', '!', '.', ',')
            return Regex(
                """^(?:все\s+)?(?:хорошо|отлично|нормально|неплохо|плохо|так себе|скучно|грустно|весело|устал\w*)(?:\s+(?:спасибо|тебе|вам))?$""" +
                    """|^(?:спасибо|благодарю|пасиб\w*|спасибо большое)(?:\s+(?:тебе|вам))?$""",
            ).matches(t)
        }

        /** Приглашение к беседе: «начни разговор», «давай поговорим», «поболтаем», «поговори со мной». */
        fun isDialogOpener(text: String): Boolean {
            val t = text.trim().lowercase().replace('ё', 'е').trimEnd('.', '!', '?', ',')
            if (t.isEmpty()) return false
            return Regex(
                "^(?:(?:ну|так|а|слушай|может|хочу|давай|давайте)\\s+)*" +
                    "(?:начн(?:и|ем|емте|ите|ать)\\s+(?:разговор|беседу|диалог|общение)" +
                    "|(?:поговорим|поболтаем|пообщаемся|поговорить|поболтать)(?:\\s+(?:со\\s+мной|немного|чуть-чуть))?" +
                    "|поговори(?:те)?\\s+со\\s+мной" +
                    "|поболтай(?:те)?\\s+со\\s+мной)$"
            ).matches(t)
        }

        /** Просьба к собеседнику, которая не может быть командой: «почему…», «посоветуй…», «придумай…». */
        fun isStrongChat(text: String): Boolean =
            Regex("""^(?:а\s+|слушай[,]?\s+)?(?:почему|зачем|посоветуй|придумай|сочини|объясни|поговори со мной|давай поговорим|как думаешь|что думаешь|ответь мне|ответь честно|ответь на вопрос|скажи честно)(?:\s|$|,|:)""")
                .containsMatchIn(text.trim().lowercase().replace('ё', 'е'))

        /**
         * Системный промпт для модели на телефоне. Каждый лишний десяток слов здесь — это задержка
         * перед первым словом ответа (модель читает промпт целиком), поэтому текст максимально короткий:
         * только правила, без которых она отвечает неправильно.
         */
        fun systemPrompt(assistantName: String, userName: String?, tone: String = ""): String {
            // Род берём из имени: «Джарвис» говорит о себе «записал», «Нова» — «записала».
            val male = ai.nova.core.nlp.Gender.ofAssistant(assistantName).isMasculine
            val selfMask = if (male) "мужского" else "женского"
            val userMask = when (ai.nova.core.nlp.Gender.of(userName)) {
                ai.nova.core.nlp.Gender.FEMININE -> "Это женщина — обращайся к ней в женском роде."
                ai.nova.core.nlp.Gender.MASCULINE -> "Это мужчина — обращайся к нему в мужском роде."
                else -> ""
            }
            return "Ты — $assistantName, голосовой ассистент. По-русски, от $selfMask лица, коротко: 1–2 предложения, " +
                // Создателя называет разбор команд, а не модель: маленькая модель врёт про Google.
                "без списков. Отвечай только на заданный вопрос. Ты не ${if (male) "создан" else "создана"} Google, OpenAI или Alibaba. " +
                "Не знаешь — скажи честно. Не здоровайся в ответ — сразу по делу. " +
                (userName?.let { "Собеседника зовут $it. $userMask " } ?: "") +
                // Маленькая модель слушается инструкции, стоящей последней.
                (if (tone.isNotBlank()) "Стиль: $tone" else "")
        }
    }
}
