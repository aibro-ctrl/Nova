    @Test fun corpusIsReadAloudCleanly() {
        assertTrue(corpus.size >= 100, "фраз в наборе: ${corpus.size}")
        for (text in corpus) {
            val spoken = SpeechText.forSpeech(text)
            assertTrue(spoken.isNotBlank(), "пустая озвучка для: $text")
            assertFalse(spoken.contains('*') || spoken.contains('#') || spoken.contains('`'), "в озвучке осталась разметка: $spoken")
            assertFalse(spoken.contains('\u0301'), "в озвучке остался знак ударения: $spoken")
            // Значение и знаки валют и градусов читаются словами, а не остаются символами.
            for (symbol in listOf('₽', '\$', '€', '%', '°')) {
                assertFalse(spoken.contains(symbol), "в озвучке остался символ $symbol: $spoken")
            }
            println("$text\n  → $spoken")
        }
    }

    /** Числа после нормализации произносятся словами: движку остаётся только прочитать текст. */
    @Test fun numbersAreWords() {
        val samples = listOf(
            "Я потратил 500 ₽ на обед", "Купи 2 кг картофеля", "Ветер 60 км/ч", "Скидка 25%",
            "На улице +12°", "Осталось 2 дня", "Встреча в 18:30", "Он пробежал 10 км",
        )
        for (text in samples) {
            val spoken = SpeechText.forSpeech(text)
            assertFalse(Regex("""\d""").containsMatchIn(spoken), "цифры остались в тексте для речи: $spoken")
        }
    }
